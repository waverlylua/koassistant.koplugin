local script = debug.getinfo(1, "S").source:sub(2)
local root = script:match("^(.*)/tests/unit/") or "."
package.path = root .. "/?.lua;" .. root .. "/tests/lib/?.lua;" .. package.path
local T = require("test_runner"):new()
local Queue = require("koassistant_question_queue")

local function harness(saved)
    local h = { scheduled = {}, starts = {}, saved = saved, now = 100 }
    h.deps = {
        load = function() return h.saved and Queue.copy(h.saved) end,
        save = function(data)
            if h.fail_save then return nil, "disk full" end
            h.saved = Queue.copy(data)
            return true
        end,
        now = function() h.now = h.now + 1; return h.now end,
        schedule = function(fn) h.scheduled[#h.scheduled + 1] = fn end,
        start = function(job, finish, register_cancel)
            h.starts[#h.starts + 1] = { job = job, finish = finish }
            register_cancel(function() h.cancelled = true; finish(false, nil, "cancelled") end)
        end,
    }
    h.queue = Queue:new(h.deps)
    function h:tick()
        local todo = self.scheduled; self.scheduled = {}
        for _, fn in ipairs(todo) do fn() end
    end
    return h
end
local function snapshot(text, path)
    return { messages = {{ role = "user", content = text or "hello" }}, config = { provider = "mock", model = "frozen" },
        selected_text = text or "hello", document = { file = path or "/book.pdf", page = 2, pos0 = {page=2,x=1} } }
end

T:test("enqueue persists before dispatch and returns immediately", function()
    local h = harness()
    local job = assert(h.queue:enqueue(snapshot()))
    T:assertEqual(#h.starts, 0)
    T:assertEqual(h.saved.jobs[1].state, "queued")
    h:tick()
    T:assertEqual(h.saved.jobs[1].state, "running")
    T:assertEqual(job.attempts, 1)
    T:assertEqual(#h.starts, 1)
end)
T:test("multiple jobs are serial and preserve immutable context across navigation", function()
    local h, a, b = harness(), snapshot("first", "/one.epub"), snapshot("second", "/two.pdf")
    h.queue:enqueue(a); h.queue:enqueue(b)
    a.document.page = 99; a.messages[1].content = "wrong"; b.config.model = "changed"
    h:tick()
    T:assertEqual(#h.starts, 1)
    T:assertEqual(h.starts[1].job.document.page, 2)
    h.starts[1].finish(true, "first answer")
    h:tick()
    T:assertEqual(#h.starts, 2)
    T:assertEqual(h.starts[2].job.config.model, "frozen")
    T:assertEqual(h.starts[2].job.document.file, "/two.pdf")
    T:assertEqual(h.queue:counts().unread, 1)
end)
T:test("completion persists answers without any open dialog", function()
    local h = harness(); h.queue:enqueue(snapshot()); h:tick()
    h.starts[1].finish(true, "answer", nil, "reason", {tokens=10})
    T:assertEqual(h.saved.jobs[1].answer, "answer")
    T:assertEqual(h.saved.jobs[1].state, "completed")
    local reloaded = harness(h.saved)
    T:assertEqual(reloaded.queue:counts().unread, 1)
    reloaded.queue:markRead("1")
    T:assertEqual(reloaded.saved.jobs[1].read, true)
end)
T:test("queued cancellation never starts a request", function()
    local h = harness(); h.queue:enqueue(snapshot()); h.queue:cancel("1"); h:tick()
    T:assertEqual(#h.starts, 0)
    T:assertEqual(h.saved.jobs[1].state, "cancelled")
end)
T:test("in-flight cancellation terminates and late success cannot revive job", function()
    local h = harness(); h.queue:enqueue(snapshot()); h:tick(); h.queue:cancel("1")
    T:assertTrue(h.cancelled)
    h.starts[1].finish(true, "late answer")
    T:assertEqual(h.saved.jobs[1].state, "cancelled")
    T:assertEqual(h.saved.jobs[1].answer, nil)
end)
T:test("retry is explicit and old-attempt completion cannot overwrite new answer", function()
    local h = harness(); h.queue:enqueue(snapshot()); h:tick(); h.queue:cancel("1")
    h.queue:retry("1"); h:tick()
    T:assertEqual(#h.starts, 2)
    h.starts[1].finish(true, "wrong")
    T:assertEqual(h.queue:get("1").state, "running")
    h.starts[2].finish(true, "right")
    T:assertEqual(h.saved.jobs[1].answer, "right")
    T:assertEqual(h.saved.jobs[1].attempts, 2)
end)
T:test("failed response never automatically retries", function()
    local h = harness(); h.queue:enqueue(snapshot()); h:tick()
    h.starts[1].finish(false, nil, "HTTP 429")
    h:tick(); h:tick()
    T:assertEqual(#h.starts, 1)
    T:assertEqual(h.saved.jobs[1].error, "HTTP 429")
end)
T:test("empty success is recoverable failure", function()
    local h = harness(); h.queue:enqueue(snapshot()); h:tick()
    h.starts[1].finish(true, "")
    T:assertEqual(h.saved.jobs[1].state, "failed")
end)
T:test("restart interrupts both running and unsent queued jobs without replay", function()
    local h = harness(); h.queue:enqueue(snapshot()); h.queue:enqueue(snapshot()); h:tick()
    local reloaded = harness(h.saved); reloaded:tick()
    T:assertEqual(#reloaded.starts, 0)
    T:assertEqual(reloaded.queue:get("1").state, "interrupted")
    T:assertEqual(reloaded.queue:get("2").state, "interrupted")
    reloaded.queue:retry("2"); reloaded:tick()
    T:assertEqual(#reloaded.starts, 1)
end)
T:test("suspend stops active work; wake only continues never-sent session jobs", function()
    local h = harness(); h.queue:enqueue(snapshot()); h.queue:enqueue(snapshot()); h:tick()
    h.queue:suspend(); h:tick()
    T:assertEqual(#h.starts, 1)
    T:assertEqual(h.queue:get("1").state, "interrupted")
    h.queue:resume(); h:tick()
    T:assertEqual(#h.starts, 2)
    T:assertEqual(h.starts[2].job.id, "2")
end)
T:test("failed enqueue persistence never dispatches", function()
    local h = harness(); h.fail_save = true
    local job, err = h.queue:enqueue(snapshot()); h:tick()
    T:assertEqual(job, nil); T:assertEqual(err, "disk full"); T:assertEqual(#h.starts, 0)
end)
T:test("failed send-intent persistence never dispatches", function()
    local h = harness(); h.queue:enqueue(snapshot()); h.fail_save = true; h:tick()
    T:assertEqual(#h.starts, 0)
    T:assertEqual(h.queue:get("1").state, "interrupted")
end)
T:test("unknown journal versions are left untouched", function()
    local h = harness({ version = 99, jobs = {} })
    T:assertTrue(h.queue.storage_error ~= nil)
    T:assertEqual(h.saved.version, 99)
end)
T:test("transport exceptions fail safely and let next job progress", function()
    local h = harness()
    h.deps.start = function() error("transport failed") end
    h.queue:enqueue(snapshot()); h.queue:enqueue(snapshot()); h:tick(); h:tick()
    T:assertEqual(h.queue:get("1").state, "failed")
    T:assertEqual(h.queue:get("2").state, "failed")
end)
T:test("malformed job entries fail closed without overwriting the journal", function()
    local h = harness({ version = 1, next_id = 2, jobs = { 1 } })
    T:assertTrue(h.queue.load_error)
    T:assertEqual(h.saved.jobs[1], 1)
    T:assertEqual(h.queue:retrySave(), nil)
end)
T:test("failed result save retains readable answer; local save retry submits nothing twice", function()
    local h = harness(); h.queue:enqueue(snapshot()); h.queue:enqueue(snapshot()); h:tick()
    h.fail_save = true; h.starts[1].finish(true, "keep me")
    T:assertEqual(h.queue:get("1").answer, "keep me")
    h:tick(); T:assertEqual(#h.starts, 1)
    h.fail_save = false; assert(h.queue:retrySave())
    T:assertEqual(h.saved.jobs[1].answer, "keep me")
    h:tick(); T:assertEqual(#h.starts, 2)
    T:assertEqual(h.starts[2].job.id, "2")
end)
T:test("only inactive jobs can be removed and removal persists", function()
    local h = harness(); h.queue:enqueue(snapshot()); h:tick()
    T:assertEqual(h.queue:remove("1"), nil)
    h.starts[1].finish(true, "answer")
    assert(h.queue:remove("1"))
    T:assertEqual(#h.saved.jobs, 0)
    T:assertEqual(h.queue:counts().unread, 0)
end)
T:test("failed removal persistence restores the readable answer", function()
    local h = harness(); h.queue:enqueue(snapshot()); h:tick(); h.starts[1].finish(true, "answer")
    h.fail_save = true
    T:assertEqual(h.queue:remove("1"), nil)
    T:assertEqual(h.queue:get("1").answer, "answer")
end)
return T:summary()
