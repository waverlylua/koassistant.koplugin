local function render(name,body,magic,resources)
 local ok,err=pcall(function()
  local doc=M.openDocumentFromText(body,magic,resources);doc:layoutDocument(600,400,22);local p=doc:openPage(1);local bb=p:draw_new(DC.new(),600,400,0,0);bb:writePNG(root..'/'..name..'.png');bb:free();p:close();doc:close()
 end)
 print(name,ok,tostring(err))
end
